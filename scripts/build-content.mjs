import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// Dependency order. The page script is one classic file: x.com's script-src
// blocks the relative imports inside a dynamically imported extension module.
const FILES = [
  "src/data/places.js",
  "src/lib/normalize.js",
  "src/lib/rules.js",
  "src/lib/ranges.js",
  "src/lib/validate.js",
  "src/lib/migrate.js",
  "src/lib/css-sanitize.js",
  "src/lib/cache.js",
  "src/lib/sync.js",
  "src/lib/storage.js",
  "src/lib/signals.js",
  "src/lib/apply.js",
  "src/lib/dom.js",
  "src/page/scanner.js",
  "src/page/main.js",
];

function importClosed(text) {
  return (
    /from\s+["'][^"']+["']\s*;?\s*$/.test(text) ||
    /^\s*import\s+["'][^"']+["']\s*;?\s*$/.test(text)
  );
}

export function stripModule(source, filename) {
  const lines = source.split("\n");
  const out = [];
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\s*import\b/.test(line)) {
      let block = line;
      while (!importClosed(block)) {
        i += 1;
        if (i >= lines.length) throw new Error(`${filename} has an import that does not end`);
        block += `\n${lines[i]}`;
      }
      continue;
    }
    if (/^\s*export\s+\{/.test(line)) {
      if (!/\}\s*;?\s*$/.test(line)) throw new Error(`${filename} has a multiline export list`);
      continue;
    }
    const stripped = line.replace(
      /^(\s*)export\s+(?=(?:async\s+)?(?:function|const|let|class|var)\b)/,
      "$1",
    );
    if (/^\s*export\b/.test(stripped)) {
      throw new Error(`${filename} has an unsupported export: ${line}`);
    }
    out.push(stripped);
  }
  return `${out.join("\n").trim()}\n`;
}

export function buildContentSource() {
  const parts = FILES.map((file) => stripModule(readFileSync(resolve(root, file), "utf8"), file));
  return `/* Generated by scripts/build-content.mjs. Edit the modules under src/, then rebuild. */\n(() => {\n"use strict";\n${parts.join("\n")}start();\n})();\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const target = resolve(root, "src/page/content.js");
  writeFileSync(target, buildContentSource());
}
