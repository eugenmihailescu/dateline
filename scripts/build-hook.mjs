import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export function buildHookSource() {
  const library = readFileSync(resolve(root, "src/lib/graphql.js"), "utf8")
    .replace(/\nexport \{[\s\S]*$/, "\n");
  const main = readFileSync(resolve(root, "src/page/hook-main.js"), "utf8");
  return `/* Generated by scripts/build-hook.mjs. Edit graphql.js or hook-main.js, then rebuild. */\n(() => {\n${library}\n${main}})();\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const target = resolve(root, "src/page/net-hook.js");
  writeFileSync(target, buildHookSource());
}
